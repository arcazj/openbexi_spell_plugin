def upstream_fault_code(body):
    if type(body) is not dict or set(body) != {"error"}:
        return "unexpected_error_shape"
    code = body["error"]
    return code if type(code) is str and code in RPC_FAULT_CODES else "unlisted_fault_code"


def failure_record(path, phase, status, upstream_code, started_ns, cpu_started_ns):
    # Allocate only on failure. Each exception owns one bounded record; no
    # successful-call closure, global event buffer, body or endpoint is retained.
    cpu_ns = time.thread_time_ns() - cpu_started_ns
    finished_ns = time.monotonic_ns()
    return dict(
        schema="openbexi.rpc-failure/1",
        path=path,
        phase=phase,
        http_status=status,
        upstream_code=upstream_code,
        started_ns=started_ns,
        finished_ns=finished_ns,
        thread_cpu_ns=cpu_ns,
    )
